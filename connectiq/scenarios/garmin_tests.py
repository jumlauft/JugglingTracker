#!/usr/bin/env python3
"""Writes ../test/ScenarioTest.mc from the scenario files in this folder.

Monkey C has no JSON reader for files in a test build, so the Garmin replays
the shared scenarios as generated code: one test function per scenario, one
ScenarioRunner call per step. Run this after changing a scenario:

    python3 connectiq/scenarios/garmin_tests.py

simulation/test_detection.py fails when the checked-in ScenarioTest.mc is out
of date, so CI catches a forgotten run even though the Garmin tests
themselves only run on a Mac (connectiq/run_tests.sh).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUTPUT = os.path.join(HERE, "..", "test", "ScenarioTest.mc")
DEFAULT_EPOCH = 1700000000


def scenarios():
    """(stem, scenario) for every scenario the Garmin runs, sorted by name."""
    out = []
    for name in sorted(os.listdir(HERE)):
        if not name.endswith(".json"):
            continue
        with open(os.path.join(HERE, name)) as f:
            scenario = json.load(f)
        platforms = scenario.get("platforms")
        if platforms is not None and "garmin" not in platforms:
            continue
        out.append((name[: -len(".json")], scenario))
    return out


def test_name(stem):
    return "scenario_" + stem


def literal(value):
    """A Monkey C literal for a JSON value."""
    if value is None:
        return "null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, int):
        if not -2**31 <= value < 2**31:
            raise ValueError(f"{value} does not fit a Monkey C Number")
        return str(value)
    if isinstance(value, float):
        return repr(value) + "f"
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, list):
        return "[" + ", ".join(literal(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{json.dumps(k)} => {literal(v)}" for k, v in value.items()) + " }"
    raise ValueError(f"no Monkey C literal for {value!r}")


def call(step):
    """The ScenarioRunner call for one step."""
    keys = [k for k in step if k != "index"]
    if len(keys) != 1:
        raise ValueError(f"a step needs exactly one key: {step}")
    key = keys[0]
    value = step[key]
    if key == "press":
        return f"r.press({literal(value)});"
    if key == "select":
        return f"r.select({literal(value)});"
    if key == "warmup":
        return "r.warmup();"
    if key in ("catches", "burst", "idle", "wait", "epochAdvance"):
        return f"r.{key}({literal(value)});"
    if key == "deliver":
        if "index" in step:
            return f"r.deliverAt({literal(value)}, {literal(step['index'])});"
        return f"r.deliver({literal(value)});"
    if key == "deliverAll":
        return "r.deliverAll();"
    if key == "relaunch":
        return "r.relaunch();"
    if key == "phone":
        return f"r.phone({literal(value)});"
    if key == "expect":
        return f"r.expect({literal(value)});"
    raise ValueError(f"unknown step {key}")


def generate():
    lines = [
        "// GENERATED by connectiq/scenarios/garmin_tests.py from connectiq/scenarios/*.json.",
        "// Do not edit: change the scenario and run the script again.",
        "",
        "import Toybox.Lang;",
        "import Toybox.Test;",
    ]
    for stem, scenario in scenarios():
        epoch = scenario.get("epochSeconds", DEFAULT_EPOCH)
        lines += [
            "",
            f"// {scenario['name']} ({', '.join(scenario['requirements'])})",
            "(:test)",
            f"function {test_name(stem)}(logger as Logger) as Boolean {{",
            f"    var r = new ScenarioRunner({literal(epoch)});",
        ]
        lines += ["    " + call(step) for step in scenario["steps"]]
        lines += ["    return r.passed(logger);", "}"]
    return "\n".join(lines) + "\n"


def main():
    with open(OUTPUT, "w") as f:
        f.write(generate())
    print(f"wrote {os.path.relpath(OUTPUT)} ({len(scenarios())} scenarios)")


if __name__ == "__main__":
    sys.exit(main())
